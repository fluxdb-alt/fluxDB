// PostgreSQL 数据编辑提交 apply_changes（T09）。
//
// 对齐 mysql/sqlite：删 → 更新 → 插入，单事务内执行，任何一步失败整体回滚。
// `pg_connect` 每次拨一条全新连接（非注册表复用），因此在本会话上 `BEGIN…COMMIT`
// 不会与其它请求串事务；语句经 `&Client` 顺序执行，错误时 `ROLLBACK` 兜底。
// PG 不经过 sqlx QueryBuilder：SQL 自行拼接，值一律 `$n` 参数化绑定，标识符 `SqlDialect::quote_identifier`。
// 二进制（bytea）写入以 `Vec<u8>` 直接绑定或按块追加（流式上传），见 `pg_apply_blob_stream`。

/// 把 tokio-postgres/PG 服务端错误转成可读文本。
///
/// 注意：tokio-postgres **外层** `Error` 的 Display 对 DB 错误只打常量 `"db error"`，
/// 真正的服务端报文（`severity: message` + DETAIL + HINT）在底层 `DbError` 里，
/// 必须经 `as_db_error()` 取到 `DbError` 用它显示，再前置 SQLSTATE 错误码。
/// 若直接显示外层 error 会得到没头没尾的 "db error"。
fn pg_db_error_text(error: &tokio_postgres::Error) -> String {
    match error.as_db_error() {
        Some(db) => format!("[SQLSTATE {}] {}", db.code().code(), db),
        None => error.to_string(),
    }
}

fn pg_apply_changes(
    config: &ConnectionConfig,
    changes: &DataChangeSet,
) -> fluxdb_core::Result<AppliedChangeOutcome> {
    validate_data_changes(changes)?;

    let database = changes
        .object
        .database
        .as_deref()
        .ok_or_else(|| Error::new(ErrorKind::Query, "缺少数据库名称"))?;

    pg_runtime().block_on(async {
        let table = pg_qualified_table(database, changes.object.schema.as_deref(), &changes.object.name);
        tracing::debug!(target: "fluxdb_connectors", table = %table, deletes = changes.deletes.len(), updates = changes.updates.len(), inserts = changes.inserts.len(), "pg_apply_changes:begin");
        let session = pg_connect(config, database).await?;
        let client = session.client.as_ref();
        // 先取列元数据（元数据查询与事务解耦）。
        let columns = pg_columns(client, database, changes.object.schema.as_deref(), &changes.object.name)
            .await?;
        // 服务端生成列（generated/identity）不可写：插入时排除、更新时拒绝。
        let generated = pg_generated_columns(client, database, changes.object.schema.as_deref(), &changes.object.name)
            .await?;

        client
            .batch_execute("BEGIN")
            .await
            .map_err(|error| Error::new(ErrorKind::Query, pg_db_error_text(&error)))?;

        let result = async {
            pg_apply_deletes(client, &table, changes, &columns).await?;
            pg_apply_updates(client, &table, changes, &columns, &generated).await?;
            let inserted_identities =
                pg_apply_inserts(client, &table, changes, &columns, &generated).await?;
            Ok::<_, fluxdb_core::Error>(AppliedChangeOutcome {
                inserted_identities,
            })
        }
        .await;

        match result {
            Ok(outcome) => {
                match client
                    .batch_execute("COMMIT")
                    .await
                    .map_err(pg_commit_error)
                {
                    Ok(()) => {
                        tracing::info!(target: "fluxdb_connectors", table = %table, deletes = changes.deletes.len(), updates = changes.updates.len(), inserts = changes.inserts.len(), "pg_apply_changes:commit");
                        Ok(outcome)
                    }
                    Err(error) => {
                        let _ = client.batch_execute("ROLLBACK").await;
                        tracing::warn!(target: "fluxdb_connectors", table = %table, message = %error.message, "pg_apply_changes:commit-failed");
                        Err(error)
                    }
                }
            }
            Err(error) => {
                let _ = client.batch_execute("ROLLBACK").await;
                tracing::warn!(target: "fluxdb_connectors", table = %table, message = %error.message, deletes = changes.deletes.len(), updates = changes.updates.len(), inserts = changes.inserts.len(), "pg_apply_changes:aborted");
                Err(error)
            }
        }
    })
}

/// 查询服务端生成列（`GENERATED ... AS` 或 `GENERATED BY DEFAULT/ALWAYS AS IDENTITY`）。
/// 这类列由数据库生成，写入会失败或语义错误，插入列列表须剔除、更新 SET 须拒绝。
async fn pg_generated_columns(
    client: &tokio_postgres::Client,
    database: &str,
    schema: Option<&str>,
    table: &str,
) -> fluxdb_core::Result<std::collections::BTreeSet<String>> {
    let _ = database;
    let schema_name = schema.unwrap_or("public");
    let rows = client
        .query(
            r#"
            SELECT a.attname
            FROM pg_attribute a
            JOIN pg_class c ON c.oid = a.attrelid
            JOIN pg_namespace n ON n.oid = c.relnamespace
            WHERE c.relname = $1 AND n.nspname = $2
              AND a.attnum > 0 AND NOT a.attisdropped
              AND (a.attgenerated <> '' OR a.attidentity <> '')
            "#,
            &[&table, &schema_name],
        )
        .await
        .map_err(pg_error)?;
    Ok(rows.into_iter().map(|row| row.get(0)).collect())
}

/// 解析一行插入值：按表列序返回需写入的 `(列, 值)`。
///
/// 未提供三态意图时退回 `non_null_insert_values` 旧语义（NULL 视为省略 → DEFAULT）；
/// 提供意图时按列对齐，`Default` 省略、`Null` 显式写 NULL、`Value` 写具体值，
/// 从而能对带默认值/可空的列显式写 NULL。服务端生成列一律剔除。
fn pg_insert_values<'a>(
    row: &'a Row,
    columns: &'a [Column],
    generated: &std::collections::BTreeSet<String>,
    intents: Option<&'a [WriteValue]>,
) -> fluxdb_core::Result<Vec<(&'a Column, &'a CellValue)>> {
    let Some(intents) = intents else {
        return Ok(non_null_insert_values(row, columns)?
            .into_iter()
            .filter(|(column, _)| !generated.contains(&column.name))
            .collect());
    };
    if intents.len() != columns.len() {
        return Err(Error::new(ErrorKind::Internal, "插入写入意图与列数不匹配"));
    }
    let mut out = Vec::new();
    for (column, intent) in columns.iter().zip(intents) {
        if generated.contains(&column.name) {
            continue; // 服务端生成列不可写
        }
        match intent {
            WriteValue::Default => {} // 省略 → 数据库默认值填充
            WriteValue::Null => out.push((column, &CellValue::Null)),
            WriteValue::Value(value) => out.push((column, value)),
        }
    }
    Ok(out)
}

/// 插入行并回传真实身份（§8.4/R11）。
///
/// 自增/序列/默认值生成的主键无法从编辑输入得知，故 INSERT 追加 `RETURNING` 主键列，
/// 用服务端返回值构造行身份——补偿 SQL 才能定位到真正插入的那一行。
async fn pg_apply_inserts(
    client: &tokio_postgres::Client,
    table: &str,
    changes: &DataChangeSet,
    columns: &[Column],
    generated: &std::collections::BTreeSet<String>,
) -> fluxdb_core::Result<Vec<RowIdentity>> {
    let primary_keys = columns
        .iter()
        .filter(|column| column.primary_key)
        .map(|column| (column.name.clone(), column.clone()))
        .collect::<Vec<_>>();
    let mut identities = Vec::with_capacity(changes.inserts.len());
    for (index, row) in changes.inserts.iter().enumerate() {
        // 清除服务端生成列（其值由数据库产生）；意图三态时逐列对齐，
        // 否则退回旧语义（NULL 视为省略 → DEFAULT）。
        let insert_values = pg_insert_values(row, columns, generated, changes.insert_intents_for(index))?;
        let (sql, params) = pg_insert_sql(table, &insert_values)?;
        if primary_keys.is_empty() {
            client
                .execute(&sql, &pg_params_refs(&params))
                .await
                .map_err(|error| Error::new(ErrorKind::Query, pg_db_error_text(&error)))?;
            continue;
        }
        let returning = primary_keys
            .iter()
            .map(|(name, _)| format!("{}::text", fluxdb_core::PostgresDialect.quote_identifier(name)))
            .collect::<Vec<_>>()
            .join(", ");
        let sql = format!("{sql} RETURNING {returning}");
        let returned = client
            .query(&sql, &pg_params_refs(&params))
            .await
            .map_err(|error| Error::new(ErrorKind::Query, pg_db_error_text(&error)))?;
        let Some(returned) = returned.into_iter().next() else {
            continue;
        };
        let mut values = std::collections::BTreeMap::new();
        for (position, (name, column)) in primary_keys.iter().enumerate() {
            values.insert(name.clone(), pg_projected_cell_value(&returned, position, column));
        }
        identities.push(RowIdentity { values });
    }
    Ok(identities)
}

async fn pg_apply_updates(
    client: &tokio_postgres::Client,
    table: &str,
    changes: &DataChangeSet,
    columns: &[Column],
    generated: &std::collections::BTreeSet<String>,
) -> fluxdb_core::Result<()> {
    for update in &changes.updates {
        if update.cells.is_empty() {
            continue;
        }
        for cell in &update.cells {
            ensure_column_exists(&cell.column, columns)?;
            // 服务端生成列不可写：拒绝，避免覆盖数据库生成值。
            if generated.contains(&cell.column) {
                return Err(Error::new(
                    ErrorKind::Query,
                    format!("生成列不可直接修改: {}", cell.column),
                ));
            }
        }
        validate_identity(&update.identity, columns)?;

        let (plain, streamed) = split_update_cells(update);
        let location = pg_lock_original_row(client, table, &update.identity, columns).await?;
        if !plain.is_empty() {
            let (mut sql, mut params) = pg_update_sql(table, &plain, &update.identity, columns)?;
            pg_append_row_location(&mut sql, &mut params, location.clone());
            // 行数检查：期望恰好 1 行。0 行=目标消失/并发冲突，>1=身份不唯一；均回滚。
            let affected = client
                .execute(&sql, &pg_params_refs(&params))
                .await
                .map_err(|error| Error::new(ErrorKind::Query, pg_db_error_text(&error)))?;
            if affected != 1 {
                return Err(update_conflict_error(affected));
            }
        }

        for (cell, stream) in streamed {
            pg_apply_blob_stream(client, table, cell, stream, &update.identity, columns, &location)
                .await?;
        }
    }
    Ok(())
}

/// 流式写入一个大字段单元格：先清空，再按块 `c = COALESCE(c, …) || $1` 追加。
///
/// 文本列用 `''::text` 起点、二进制列用 `''::bytea`：bytea 不能用文本空串拼接
/// （类型不匹配），text 列也不接受 bytea 参数。分块边界已由 `streamed_chunk_at`
/// 对齐到 UTF-8 字符边界，因此每一块都是合法文本。
///
/// 注意代价：bytea/text 都是不可变值，每次追加都由服务端重写整值，整体是 O(n²)。
/// 这就是分块取 [`fluxdb_core::BLOB_STREAM_CHUNK_BYTES`]（16 MiB）而不用几 MB 的原因；
/// 真流式需要 `lo_*` 大对象 API，跨驱动不可移植，此处不做。
///
/// 事务内已经 `FOR UPDATE` 锁住目标行，因此这里仍逐块带行位置条件，任何一块没命中
/// 唯一行都直接失败并整体回滚。
async fn pg_apply_blob_stream(
    client: &tokio_postgres::Client,
    table: &str,
    cell: &fluxdb_core::CellUpdate,
    stream: &fluxdb_core::StreamedValue,
    identity: &RowIdentity,
    columns: &[Column],
    location: &(u32, String),
) -> fluxdb_core::Result<()> {
    let quoted = fluxdb_core::SqlDialect::quote_identifier(&fluxdb_core::PostgresDialect, &cell.column);
    let is_text = stream.is_text();
    // 清空：用空串/空 bytea 而不是 NULL，目标列可能是 NOT NULL。
    let empty = if is_text { "''::text" } else { "''::bytea" };
    let (where_sql, mut clear_params) = pg_identity_params(identity, columns)?;
    let mut sql = format!("UPDATE {table} SET {quoted} = {empty}{where_sql}");
    pg_append_row_location(&mut sql, &mut clear_params, location.clone());
    let affected = client
        .execute(&sql, &pg_params_refs(&clear_params))
        .await
        .map_err(|error| Error::new(ErrorKind::Query, pg_db_error_text(&error)))?;
    require_single_streamed_row(affected, &cell.column)?;

    // 读一块、发一条：tokio-postgres 不支持把 bytea 参数分片发送，只能按块重复
    // 执行语句，进程内存峰值等于一块。
    let mut offset = 0u64;
    while let Some(chunk) = streamed_chunk_at(stream, offset)? {
        let chunk_len = chunk.len() as u64;
        let (where_sql, mut params) = pg_identity_params(identity, columns)?;
        let cast = if is_text { "::text" } else { "::bytea" };
        let param: Box<dyn ToSql + Sync> = if is_text {
            Box::new(String::from_utf8(chunk).map_err(|_| {
                Error::new(
                    ErrorKind::Unsupported,
                    "待写入文本不是合法的 UTF-8，已取消提交",
                )
            })?)
        } else {
            Box::new(chunk)
        };
        params.push(param);
        let chunk_index = params.len();
        let mut sql = format!(
            "UPDATE {table} SET {quoted} = COALESCE({quoted}, {empty}) || ${chunk_index}{cast}{where_sql}"
        );
        pg_append_row_location(&mut sql, &mut params, location.clone());
        let affected = client
            .execute(&sql, &pg_params_refs(&params))
            .await
            .map_err(|error| Error::new(ErrorKind::Query, pg_db_error_text(&error)))?;
        require_single_streamed_row(affected, &cell.column)?;
        // 按实际读到的长度推进，不能按请求长度：存储可能提前返回较短的块。
        offset += chunk_len;
    }
    Ok(())
}

async fn pg_apply_deletes(
    client: &tokio_postgres::Client,
    table: &str,
    changes: &DataChangeSet,
    columns: &[Column],
) -> fluxdb_core::Result<()> {
    for identity in &changes.deletes {
        validate_identity(identity, columns)?;
        let location = pg_lock_original_row(client, table, identity, columns).await?;
        let (where_sql, mut params) = pg_identity_params(identity, columns)?;
        let mut sql = format!("DELETE FROM {table}{where_sql}");
        pg_append_row_location(&mut sql, &mut params, location);
        // 行数检查：期望恰好 1 行，0/>1 均视为并发冲突或身份不唯一，整体回滚。
        let affected = client
            .execute(&sql, &pg_params_refs(&params))
            .await
            .map_err(|error| Error::new(ErrorKind::Query, pg_db_error_text(&error)))?;
        if affected != 1 {
            return Err(update_conflict_error(affected));
        }
    }
    Ok(())
}

/// 更新/删除影响行数与期望不符时的并发冲突错误（设计 7.3：0 行消失、>1 身份不唯一）。
fn update_conflict_error(affected: u64) -> fluxdb_core::Error {
    let message = if affected == 0 {
        "目标行已不存在或已被并发修改，已回滚本次提交".to_string()
    } else {
        "行身份不唯一，命中了多行，已回滚本次提交".to_string()
    };
    Error::new(ErrorKind::Query, message)
}

fn pg_insert_sql(
    table: &str,
    values: &[(&Column, &CellValue)],
) -> fluxdb_core::Result<(String, Vec<Box<dyn ToSql + Sync>>)> {
    if values.is_empty() {
        // 全部字段为 NULL 时退化为默认值插入。
        return Ok((format!("INSERT INTO {table} DEFAULT VALUES"), Vec::new()));
    }

    let mut params: Vec<Box<dyn ToSql + Sync>> = Vec::new();
    let column_list = values
        .iter()
        .map(|(column, _)| fluxdb_core::PostgresDialect.quote_identifier(&column.name))
        .collect::<Vec<_>>()
        .join(", ");
    let placeholders = values
        .iter()
        .map(|(column, value)| pg_bind_sql(&mut params, column, value))
        .collect::<Vec<_>>()
        .join(", ");
    Ok((
        format!("INSERT INTO {table} ({column_list}) VALUES ({placeholders})"),
        params,
    ))
}

fn pg_update_sql(
    table: &str,
    cells: &[&fluxdb_core::CellUpdate],
    identity: &fluxdb_core::RowIdentity,
    columns: &[Column],
) -> fluxdb_core::Result<(String, Vec<Box<dyn ToSql + Sync>>)> {
    let mut params: Vec<Box<dyn ToSql + Sync>> = Vec::new();
    let sets = cells
        .iter()
        .map(|cell| {
            let col = columns
                .iter()
                .find(|column| column.name == cell.column)
                .ok_or_else(|| Error::new(ErrorKind::Query, "更新引用了不存在的列"))?;
            Ok(format!(
                "{} = {}",
                fluxdb_core::PostgresDialect.quote_identifier(&cell.column),
                pg_bind_sql(&mut params, col, cell.value.placeholder())
            ))
        })
        .collect::<Result<Vec<_>, _>>()?
        .join(", ");
    // 身份条件继续沿用同一参数序号（紧跟 SET 之后）。
    let where_sql = pg_identity_where(&mut params, identity, columns)?;
    Ok((
        format!("UPDATE {table} SET {sets}{where_sql}"),
        params,
    ))
}

/// 把行身份写成参数化 WHERE 并追加到既有参数表（保证 `$n` 序号连续）。空身份则报错。
fn pg_identity_where(
    params: &mut Vec<Box<dyn ToSql + Sync>>,
    identity: &fluxdb_core::RowIdentity,
    columns: &[Column],
) -> fluxdb_core::Result<String> {
    let mut clauses = Vec::new();
    for (column, value) in &identity.values {
        if !columns.iter().any(|col| &col.name == column) {
            return Err(Error::new(ErrorKind::Query, "行身份引用了不存在的列"));
        }
        // 预览值（超大字段/截断文本）不是权威内容：按它拼 WHERE 只会静默命中 0 行，
        // 把并发冲突误报成“目标行已不存在”。上游应剔除这类身份；这里兜底拒绝。
        if value.is_truncated() {
            return Err(Error::new(
                ErrorKind::Unsupported,
                "行身份包含未完整加载的大字段，无法安全定位行；请刷新后重试或改用主键定位",
            ));
        }
        let quoted = fluxdb_core::PostgresDialect.quote_identifier(column);
        if matches!(value, CellValue::Null) {
            clauses.push(format!("{quoted} IS NULL"));
        } else {
            // 按服务器文本比较：列投影为 `::text`，参数也必须以 text 绑定。
            // 若用数字类型绑定（整型 PK 会序列化为 int2/int4/int8），
            // 与服务端因 `::text` 推断出的 text 参数类型不符，
            // tokio-postgres 报 “error serializing parameter 0”。
            let bound = format!("${}", params.len() + 1);
            params.push(Box::new(pg_text(value)));
            clauses.push(format!("{quoted}::text IS NOT DISTINCT FROM ({bound})::text"));
        }
    }
    if clauses.is_empty() {
        return Err(Error::new(ErrorKind::Query, "缺少行身份条件，已取消提交"));
    }
    Ok(format!(" WHERE {}", clauses.join(" AND ")))
}

/// 锁定并确认唯一候选后才执行写入；物理位置仅用于本事务，不进入历史或跨页身份。
async fn pg_lock_original_row(client: &tokio_postgres::Client, table: &str, identity: &RowIdentity, columns: &[Column]) -> fluxdb_core::Result<(u32, String)> {
    let mut params = Vec::new();
    let where_sql = pg_identity_where(&mut params, identity, columns)?;
    let rows = client.query(&format!("SELECT tableoid, ctid::text FROM {table}{where_sql} LIMIT 2 FOR UPDATE"), &pg_params_refs(&params)).await.map_err(pg_error)?;
    if rows.len() != 1 { return Err(update_conflict_error(rows.len() as u64)); }
    Ok((rows[0].get(0), rows[0].get(1)))
}

fn pg_append_row_location(sql: &mut String, params: &mut Vec<Box<dyn ToSql + Sync>>, location: (u32, String)) {
    params.push(Box::new(location.0)); let oid = params.len();
    params.push(Box::new(location.1)); let tid = params.len();
    sql.push_str(&format!(" AND tableoid = ${oid}::oid AND ctid = CAST(${tid}::text AS tid)"));
}

#[cfg(test)]
mod pg_identity_guard_tests {
    use super::*;

    /// 预览值不能拼成 WHERE：否则会静默命中 0 行，把并发冲突误报成“目标行已不存在”。
    #[test]
    fn identity_rejects_truncated_value() {
        let identity = RowIdentity {
            values: std::collections::BTreeMap::from([(
                "payload".to_string(),
                CellValue::TruncatedText {
                    preview: "前 4000 字符".to_string(),
                    total_chars: 100_000,
                },
            )]),
        };
        let columns = vec![Column {
            name: "payload".to_string(),
            type_name: Some("text".to_string()),
            nullable: true,
            primary_key: false,
            comment: None,
        }];
        let mut params: Vec<Box<dyn ToSql + Sync>> = Vec::new();

        let error = pg_identity_where(&mut params, &identity, &columns)
            .expect_err("预览身份必须被拒绝");

        assert_eq!(error.kind, ErrorKind::Unsupported);
        assert!(error.message.contains("大字段"), "{}", error.message);
    }
}
