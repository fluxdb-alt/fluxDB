// 动态错误模板：按字面片段与占位符顺序匹配，参数值保持原样。

fn match_backend_template<'a>(text: &'a str, template: &str) -> Option<Vec<&'a str>> {
    let parts = template.split("{}").collect::<Vec<_>>();
    if parts.len() == 1 {
        return (text == template).then(Vec::new);
    }
    let mut rest = text.strip_prefix(parts[0])?;
    let mut values = Vec::with_capacity(parts.len() - 1);
    for (index, part) in parts.iter().enumerate().skip(1) {
        if index == parts.len() - 1 {
            let value = if part.is_empty() { rest } else { rest.strip_suffix(part)? };
            values.push(value);
        } else {
            let position = rest.find(part)?;
            values.push(&rest[..position]);
            rest = &rest[position + part.len()..];
        }
    }
    Some(values)
}

